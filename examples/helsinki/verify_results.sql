SET RUN_ID = '7A2528115440';
SET CALENDAR_OBJECT = 'HELSINKI_WEATHER_LAB.KUMO_2026.PREDICTIONS_2026_' || $RUN_ID;
SET METRICS_OBJECT = 'HELSINKI_WEATHER_LAB.KUMO_2026.METRICS_2026_' || $RUN_ID;
SET HISTORY_OBJECT = 'HELSINKI_WEATHER_LAB.KUMO_2026.RECURSIVE_HISTORY_' || $RUN_ID;

SELECT * FROM IDENTIFIER($METRICS_OBJECT) ORDER BY MODEL;
SELECT STATION_ID, COUNT(*) AS N, MIN(PREDICTION_DATE) AS FIRST_DAY,
 MAX(PREDICTION_DATE) AS LAST_DAY, COUNT(ACTUAL_C) AS ACTUALS
 FROM IDENTIFIER($CALENDAR_OBJECT) GROUP BY STATION_ID ORDER BY STATION_ID;
SELECT PHASE, STATUS, COUNT(*) AS N, COUNT(ACTUAL_C) AS ACTUALS,
 COUNT(PREDICTION_C) AS PREDICTIONS, MIN(LEAD_DAYS) AS MIN_LEAD,
 MAX(LEAD_DAYS) AS MAX_LEAD
 FROM IDENTIFIER($CALENDAR_OBJECT) GROUP BY PHASE, STATUS ORDER BY PHASE;
SELECT COUNT(*) AS INVALID_PREDICTIONS
 FROM IDENTIFIER($CALENDAR_OBJECT)
 WHERE PREDICTION_C IS NULL OR PREDICTION_C::VARCHAR IN ('NaN', 'inf', '-inf');
SELECT COUNT(*) AS DUPLICATE_KEYS FROM (
 SELECT STATION_ID, PREDICTION_DATE FROM IDENTIFIER($CALENDAR_OBJECT)
 GROUP BY STATION_ID, PREDICTION_DATE HAVING COUNT(*) <> 1);
SELECT COUNT(*) AS NOV_DEC_PREDICTIONS, COUNT(ACTUAL_C) AS NOV_DEC_ACTUALS,
 COUNT_IF(STATUS <> 'FORECAST_ONLY') AS INVALID_STATUS
 FROM IDENTIFIER($CALENDAR_OBJECT) WHERE MONTH(PREDICTION_DATE) >= 11;
SELECT SOURCE_TYPE, COUNT(*) AS N, MIN(OBS_DATE) AS FIRST_DAY,
 MAX(OBS_DATE) AS LAST_DAY FROM IDENTIFIER($HISTORY_OBJECT)
 GROUP BY SOURCE_TYPE ORDER BY SOURCE_TYPE;
SELECT COUNT(*) AS SOURCE_OBSERVATIONS, MAX(OBS_DATE) AS LATEST_ACTUAL
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.OBSERVATIONS;
