-- Baselines are explicitly identified; these are not Kumo outputs.
CREATE OR REPLACE VIEW HELSINKI_WEATHER_LAB.KUMO_2026.BASELINE_CALENDAR AS
 SELECT ENTITY1 AS STATION_ID, TIMESTAMP::DATE AS PREDICTION_DATE,
        TARGET1 AS ACTUAL_C, PERSISTENCE_C, SEASONAL_2025_C,
        IFF(PHASE='ROLLING_ACTUAL_HISTORY', PERSISTENCE_C, SEASONAL_2025_C) AS BASELINE_C,
        IFF(PHASE='ROLLING_ACTUAL_HISTORY', 'PERSISTENCE', 'SEASONAL_NAIVE_2025') AS BASELINE,
        PHASE, ELIGIBLE, LEAD_DAYS
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.CALENDAR_2026;
CREATE OR REPLACE VIEW HELSINKI_WEATHER_LAB.KUMO_2026.BASELINE_METRICS AS
 SELECT 'PERSISTENCE' AS MODEL, COUNT(*) AS N,
        AVG(ABS(PERSISTENCE_C-TARGET1)) AS MAE_C,
        SQRT(AVG(POWER(PERSISTENCE_C-TARGET1,2))) AS RMSE_C
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.CALENDAR_2026
 WHERE TARGET1 IS NOT NULL AND ELIGIBLE=1 AND PERSISTENCE_C IS NOT NULL
 UNION ALL
 SELECT 'SEASONAL_NAIVE_2025', COUNT(*), AVG(ABS(SEASONAL_2025_C-TARGET1)),
        SQRT(AVG(POWER(SEASONAL_2025_C-TARGET1,2)))
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.CALENDAR_2026
 WHERE TARGET1 IS NOT NULL AND ELIGIBLE=1 AND SEASONAL_2025_C IS NOT NULL;
SELECT * FROM HELSINKI_WEATHER_LAB.KUMO_2026.BASELINE_METRICS;
SELECT PHASE, COUNT(*) AS N, COUNT(TARGET1) AS ACTUALS,
 COUNT_IF(MONTH(TIMESTAMP)>=11 AND TARGET1 IS NOT NULL) AS INVALID_FUTURE_ACTUALS
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.CALENDAR_2026 GROUP BY PHASE;
