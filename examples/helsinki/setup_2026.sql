CREATE DATABASE IF NOT EXISTS HELSINKI_WEATHER_LAB;
CREATE SCHEMA IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026;
CREATE SCHEMA IF NOT EXISTS HELSINKI_WEATHER_LAB.TRAIN_2026;
CREATE SCHEMA IF NOT EXISTS HELSINKI_WEATHER_LAB.SCORE_2026;
CREATE STAGE IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.INPUT_FILES;
CREATE STAGE IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.NOTEBOOK_FILES;
CREATE FILE FORMAT IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.CSV_INPUT
 TYPE=CSV SKIP_HEADER=1 FIELD_OPTIONALLY_ENCLOSED_BY='"' EMPTY_FIELD_AS_NULL=TRUE NULL_IF=('');
CREATE TABLE IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.STATIONS
 (STATION_ID VARCHAR, NAME VARCHAR, LATITUDE FLOAT, LONGITUDE FLOAT);
CREATE TABLE IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.OBSERVATIONS
 (OBS_ID VARCHAR, STATION_ID VARCHAR, OBS_DATE DATE, AVAILABLE_AT TIMESTAMP_NTZ, TEMP_C FLOAT);
CREATE TABLE IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.TRAINING_LABELS
 (ENTITY1 VARCHAR, TIMESTAMP TIMESTAMP_NTZ, TARGET1 FLOAT, SPLIT INTEGER);
CREATE TABLE IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.SCORE_POPULATION
 (ENTITY1 VARCHAR, TIMESTAMP TIMESTAMP_NTZ);
CREATE TABLE IF NOT EXISTS HELSINKI_WEATHER_LAB.KUMO_2026.CALENDAR_2026
 (ENTITY1 VARCHAR, TIMESTAMP TIMESTAMP_NTZ, TARGET1 FLOAT, PERSISTENCE_C FLOAT,
  SEASONAL_2025_C FLOAT, PHASE VARCHAR, ELIGIBLE INTEGER, LEAD_DAYS INTEGER);
-- Use supported string labels: decimal128 and connector-downcast float32 are rejected.
CREATE OR REPLACE VIEW HELSINKI_WEATHER_LAB.KUMO_2026.TRAINING_LABELS_KUMO AS
 SELECT ENTITY1, TIMESTAMP, TARGET1, SPLIT::VARCHAR AS SPLIT
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.TRAINING_LABELS;
CREATE OR REPLACE VIEW HELSINKI_WEATHER_LAB.TRAIN_2026.STATIONS AS
 SELECT STATION_ID, LATITUDE, LONGITUDE FROM HELSINKI_WEATHER_LAB.KUMO_2026.STATIONS;
CREATE OR REPLACE VIEW HELSINKI_WEATHER_LAB.SCORE_2026.STATIONS AS
 SELECT STATION_ID, LATITUDE, LONGITUDE FROM HELSINKI_WEATHER_LAB.KUMO_2026.STATIONS;
CREATE OR REPLACE VIEW HELSINKI_WEATHER_LAB.TRAIN_2026.DAILY_TEMPERATURES AS
 SELECT OBS_ID, STATION_ID, AVAILABLE_AT, TEMP_C
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.OBSERVATIONS
 WHERE OBS_DATE < '2026-01-01' AND TEMP_C IS NOT NULL;
CREATE OR REPLACE VIEW HELSINKI_WEATHER_LAB.SCORE_2026.DAILY_TEMPERATURES AS
 SELECT OBS_ID, STATION_ID, AVAILABLE_AT, TEMP_C
 FROM HELSINKI_WEATHER_LAB.KUMO_2026.OBSERVATIONS
 WHERE OBS_DATE <= '2026-10-28' AND TEMP_C IS NOT NULL;
